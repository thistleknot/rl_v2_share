#
#   one-call verdict-first  2b    6/10   sd 0.255   10/10
#   one-call quality-first  2b    7/10   sd 0.071   10/10
#   two-call                2b    9/10   sd 0.289   10/10
#   two-call                4b   10/10   sd 0.158   10/10   <- shipped
#
# A judge that marks 30-40% of VERIFIED GOLD as incorrect is unusable regardless of spread,
# which is what both one-call variants did. 4b at two calls recognises every gold and still
# rejects every decoy.
#
# REQ-J8 CONTAMINATION, UNRESOLVED AND RECORDED: the QA pool was generated by
# qwen3.5-reasoning-thinking-256k:9b and this judge is the 4b of the same line, so it may
# favour its own phrasings. The only non-Qwen local model is gemma-4-12b; running it as a
# cross-family check is the outstanding validation, not a solved problem.
JUDGE_MODEL = os.environ.get("JUDGE_MODEL", "qwen3.5-reasoning-thinking-256k:4b")
_REMOTE_WARNED = False       # one warning per process, not per call

# R3 QUESTIONS ARE ALL ANSWERABLE, so there is no abstention class here. Offering
# `not_attempted` as a choice made the judge file coherent-but-wrong answers under it --
# measured 2026-08-28: a full, on-topic, plainly wrong answer about boosting came back
# not_attempted, and combine() hard-zeroed it. 40 of 60 answers scored exactly 0.00 that way
# while none of them were empty. Two values only; an answer that attempts and misses is
# `incorrect`.
VERDICTS = ("correct", "incorrect")

# Sentinel for "the judge did not answer" -- a MEASUREMENT failure, not a model behaviour.
# Never offered to the model, never counted as correct.
NO_MEASUREMENT = "not_attempted"

# ── TWO CALLS. THE GOLD IS WITHHELD FROM THE QUALITY CALL. ─────────────────────────
# Quality must be judged without knowing whether the answer is right. Ordering the fields
# quality-first in ONE call only achieves POSITIONAL blindness -- the gold is still in the
# prompt, and the judge still anchors on it. Measured: one-call quality-first collapsed the
# spread to sd 0.071 AND misjudged 3 of 10 golds as incorrect.
#
# Splitting the calls gives ACTUAL blindness (call 1 never sees the gold) and makes each
# call a task a small model can do. Measured: 10/10 golds recognised, decoys still 10/10,
# spread restored.
#
# Cost is 2 requests per graded answer. That is the price of an instrument whose two axes
# are independent; a cheaper judge that cannot recognise ground truth is not cheaper.
#
# `guidance` is not needed: ollama's schema-to-GBNF already constrains the output shape, and
# the blindness comes from the PROMPT SPLIT, not from decoding order (Law 9 -- no second
# inference stack for a property we get from splitting a prompt).
_QUALITY_SCHEMA = {
    "type": "object",
    "properties": {
        "quality": {"type": "number"},
        "conciseness": {"type": "number"},
        "self_sufficient": {"type": "boolean"},
    },
    "required": ["quality", "conciseness"],
}

# THE SCORE COMES FROM THE RUBRIC, NOT FROM ARITHMETIC ON A BLIND QUALITY CALL.
# The rubric defines explicit score bands (0.0 off-topic / 0.1-0.3 related-but-not-asked /
# 0.4-0.6 plausible-and-wrong / 0.7+ correct), and the verdict call is the one that reads
# them alongside the gold. Deriving the score instead from the blind quality call put a
# fluent wrong answer at 0.70 x quality, and the quality call returns ~0 on wrong answers
# however well written -- so plausible-and-wrong collapsed onto the same 0.00 as garbage.
# Quality is still requested and reported, but as a diagnostic, not as the score.
_VERDICT_SCHEMA = {
    "type": "object",
    "properties": {
        "verdict": {"type": "string", "enum": list(VERDICTS)},
        "score": {"type": "number"},
        "why": {"type": "string"},
    },
    "required": ["verdict", "score"],
}

# ONE SCORE, NOT A VERDICT PLUS A SCORE (owner decision, 2026-08-29).
#
# Asking for a verdict AND a quality number asks the same question twice in two formats, and
# two answers that CAN disagree eventually do. Measured that day on rubric item r3-0057: the
# judge returned verdict `correct` with quality `0.0` -- a self-contradiction the two-call
# design permits by construction, which then had to be arbitrated downstream by band
# arithmetic. A single number cannot contradict itself.
#
# The judge already has everything it needs to place one number: the gold answer, the
# question, and a rubric that states the scale and says where 0.70 sits. The verdict is then
# DERIVED from the score rather than asserted alongside it, so `is_correct` and the score can
# never disagree again.
#
# This also halves the call count, which is why a 4b judge is affordable at k=8.
# FIELD ORDER IS THE MECHANISM, NOT COSMETIC. Constrained decoding emits properties in the
# order declared, so a schema of {score, why} makes the model commit to a number FIRST and
# then rationalise it -- the justification cannot inform a score that is already written.
# Every reasoning field below therefore precedes `score`, and all of them are required.
#
# The fields are not free-form "think step by step": they force the three specific readings
# the rubric actually depends on. Measured failure they close, rubric item r3-0057: the judge
# scored a procedural deferral ("Yes, proceed as described...") as correct, because nothing
# ever made it state what the gold claimed and check whether the answer said it. Having to
# write `gold_claim` and then `answer_states_gold_claim: false` makes a passing score
# self-contradictory rather than merely wrong.
_SCORE_SCHEMA = {
    "type": "object",
    "properties": {
        "reasoning": {
            "type": "string",
            "description": (
                "Work through these IN ORDER, in two or three sentences, before you place "
                "the number. (a) GOLD CLAIM: the one substantive claim the gold makes, in "
                "your own words -- read the gold before anything else. (b) ANSWER CLAIM: "
                "what the answer actually asserts; if it asserts nothing, because it "
                "agrees, defers, restates the question, or calls the approach standard, "
                "say exactly that. (c) DOES THE ANSWER STATE THE GOLD CLAIM? Sounding "
                "confident, being on-topic, or agreeing is NOT stating it -- this decides "
                "which side of 0.70 the score falls on. (d) SHORTCOMING: what keeps it off "
                "the top of its band -- padding, vagueness, a missing step, a wrong number "
                "-- or 'nothing'. This is what separates 0.72 from 0.98."
            ),
        },
        "score": {
            "type": "number",
            "description": (
                "Only now, the number, and it must agree with step (c): >= 0.70 if the "
                "answer states the gold's claim, < 0.70 if it does not."
            ),
        },
    },
    # TWO FIELDS. Operator 2026-09-16: "Its two fields / Reasoning / Score", and earlier
    # "5 fields is not KISS / Reasoning can have a description with all those individual
    # other fields mentioned as what to include in reasoning".
    #
    # The checks that used to be separate keys are now ordered steps INSIDE reasoning:
    # gold claim, answer claim, does-the-answer-state-it, shortcoming. They exist because
    # of rubric item r3-0057, where a procedural deferral ("Yes, proceed as described...")
    # scored correct -- nothing had forced the judge to state what the gold claimed and
    # check whether the answer said it. As separate fields the contradiction was
    # MECHANICAL (a boolean the score had to agree with); as prose it is a written
    # instruction, so the deferral case is re-tested rather than assumed.
    "required": ["reasoning", "score"],
}

# Correctness picks the BAND; quality positions the answer inside it. A correct answer can
# never score below an incorrect one, and quality still separates answers within each band.
#
#   correct    ->  0.70 + 0.30 * q   in [0.70, 1.00]
#   incorrect  ->  0.70 * q          in [0.00, 0.70)
#   not_attempted -> 0.0
#
# The 0.70 split is the OWNER'S CONVENTION (C-grade as passing), recorded as a convention:
# the literature has no graded->binary cut point to appeal to. Because the verdict, not the
# threshold, decides correct/incorrect, this constant only shapes the RL reward -- moving it
# cannot change a single gate result.
CORRECT_FLOOR = 0.70

_rubric_cache: dict[str, str] = {}


def load_rubric(path: str = RUBRIC_PATH) -> str:
    if path not in _rubric_cache:
        with open(path, encoding="utf-8") as f:
            _rubric_cache[path] = f.read()
    return _rubric_cache[path]


def rubric_sha(path: str = RUBRIC_PATH) -> str:
    """REQ-J9: the rubric is part of the frozen eval. Its hash goes in the receipt so a
    changed rubric cannot silently invalidate a base->CPT->SFT->RL comparison."""
    try:
        return hashlib.sha256(load_rubric(path).encode("utf-8")).hexdigest()[:16]
    except OSError:
        return "MISSING"


def instrument() -> dict:
    """Everything needed to reproduce a score. Print this beside any number it produced.

    NAMES THE JUDGE THAT ACTUALLY RAN, not the local default. This returned
    JUDGE_MODEL unconditionally, so under JUDGE_REMOTE=1 every receipt on disk
    recorded the local 4b while every call went to OpenRouter's 9b. The same bug was
    already fixed in score_arms' BANNER (see its comment: "A log that names the wrong
    instrument is worse than one that names none") -- but the RECEIPT kept the stale
    name, and on 2026-09-21 it was read back out of the JSON and reported to the
    operator as "the judge is a 4B". Operator: "Wtf you mean 4b? We use openrouter."

    A receipt exists to be read later by someone who cannot re-run the job. It must
    not name an instrument that never touched the work.
    """
    _model, _remote = JUDGE_MODEL, False
    try:
        from rlv2.judge import reward as _R
        if _R._openrouter_enabled():
            _model, _remote = _R.OPENROUTER_JUDGE_MODEL, True
    except Exception:
        pass
    return {"judge_model": _model, "judge_remote": _remote,
            "judge_model_local_default": JUDGE_MODEL,
            "rubric": RUBRIC_PATH, "rubric_sha256_16": rubric_sha()}


def build_quality_prompt(question: str, answer: str, category: str = "") -> str:
    """CALL 1. The gold is DELIBERATELY ABSENT -- do not add it back."""
    return (
        "You are grading the WRITING QUALITY of an answer. You are NOT told whether it is "
        "factually correct, and you must not guess.\n\n"
        "quality 0-1: clear, specific, committed, self-contained.\n"
        "conciseness 0-1: 1.0 tight and complete; 0.0 padded, hedged or rambling. "
        "SHORTER IS BETTER -- length is only justified by a needed derivation.\n"
        "self_sufficient: does the answer stand alone?\n\n"
        "Category: %s\nQuestion: %s\nAnswer: %s\n"
        % (category or "unspecified", question, answer if answer.strip() else "<EMPTY>")
    )


def build_score_prompt(question: str, gold: str, answer: str, category: str = "") -> str:
    """THE call. One number, placed against the rubric's scale, with the gold in hand.

    The judge is given the gold and asked where the answer sits -- not asked to rule on
    correctness and then separately rate quality. Correctness is expressed AS the score:
    0.70 and above means the answer lands the gold's claim, below means it does not. See
    `_SCORE_SCHEMA` for why the two-call form was retired.
    """
    return (
        "%s\n\n"
        "---\n"
        "Score this answer against the gold, using the scale above. WORK IN THIS ORDER and "
        "do not jump to the number:\n"
        "  1. reasoning - in order, in two or three sentences: the GOLD's one claim in "
        "your own words; what the ANSWER asserts (say so plainly if it asserts nothing, "
        "because it agrees, defers, restates the question, or calls the approach "
        "standard); whether the answer STATES the gold's claim (sounding confident or "
        "being on-topic is not stating it); and what keeps it off the top of its band, "
        "or 'nothing'.\n"
        "  2. score     - only now, the number. It must agree with what you just wrote: "
        ">= 0.70 if the answer states the gold's claim, < 0.70 if it does not.\n"
        "Do not round to 0.0, 0.5 or 1.0.\n"
        "Category: %s\nQuestion: %s\nGold: %s\nAnswer: %s\n"
        % (load_rubric(), category or "unspecified", question, gold,
           answer if answer.strip() else "<EMPTY>")
    )


def build_verdict_prompt(question: str, gold: str, answer: str, category: str = "") -> str:
    """CALL 2. Correctness only -- no quality numbers, so the two axes stay independent."""
    return (
        "%s\n\n"
        "---\n"
        "Decide the VERDICT, then place the answer on the rubric's score scale above.\n"
        "The score must sit on the side of 0.70 that your verdict implies: correct is >= 0.70, "
        "incorrect is < 0.70. A wrong answer that is on-topic, coherent and plausible belongs "
        "at 0.4-0.6 -- reserve 0.0 for an answer that is empty, degenerate, or not a plausible "
        "attempt at THIS question.\n"
        "Category: %s\nQuestion: %s\nGold: %s\nAnswer: %s\n"
        % (load_rubric(), category or "unspecified", question, gold,
           answer if answer.strip() else "<EMPTY>")
    )


class LatencyBudget:
    """Adaptive per-call timeout from an EMA of observed latency (owner design, 2026-08-30).

    WHY NOT A FIXED CAP. The judge ran with `timeout=180.0`. Measured clean on the 12 rubric
    items: median 13.7 s, mean 14.6 s, sd 3.2 s, max 22.5 s (the cold first call). A 180 s cap
    is ~13x the median, so a genuinely stuck call blocks for three minutes before anyone finds
    out -- and a call that dies is recorded `not_attempted`, which `is_correct` counts as
    wrong. That is how a Gate B trial lost an item and became a floor rather than a
    measurement.

    THE BOOTSTRAP IS DELIBERATE. Until `min_samples` real observations exist there is no
    distribution to derive from, so the cap is a fixed `bootstrap` seconds. 60 s is chosen
    from the measurement above: it clears the 22.5 s cold-load call, leaves room for the ~2x
    slowdown when OLLAMA_NUM_PARALLEL=2 calls run concurrently, and is still 3x tighter than
    the 180 s it replaces.

    ONLY SUCCESSFUL CALLS FEED THE EMA. A timeout or transport failure has no meaningful
    latency -- recording the cap itself would ratchet the budget upward every time it fired,
    which is the failure mode where a hung service slowly widens its own tolerance until the
    guard is meaningless.

    TIME EXECUTION, NOT QUEUE WAIT. With a submission queue deeper than the server's
    concurrency, a call can sit waiting through no fault of its own. The caller must start the
    clock when the request actually goes out, or the budget will evict healthy calls under
    load -- punishing depth rather than detecting a stall.
    """

    def __init__(self, bootstrap: float = 60.0, min_samples: int = 5,
                 k: float = 4.0, alpha: float = 0.3, floor: float = 15.0):
        self.bootstrap = bootstrap
        self.min_samples = min_samples
        self.k = k                       # sdev multiples above the mean before eviction
        self.alpha = alpha               # EMA weight on the newest sample
        self.floor = floor               # never cap below this, whatever the EMA says
        self.ema = None
        self.ema_var = 0.0
        self.n = 0

    def timeout(self) -> float:
        """Bootstrap is a CEILING, not just a starting point.

        The adaptive band may only ever tighten below it. Without that clamp a single slow
        SUCCESS ratchets the cap upward: measured, one 60 s sample after five ~13 s ones took
        the budget from 15.7 s to 113 s -- wider than the 60 s it started at, which defeats
        the purpose of having a budget at all. A guard that loosens itself in response to the
        symptom it exists to catch is not a guard.
        """
        if self.n < self.min_samples or self.ema is None:
            return self.bootstrap
        return min(self.bootstrap,
                   max(self.floor, self.ema + self.k * (self.ema_var ** 0.5)))

    def record(self, seconds: float) -> None:
        """Feed a SUCCESSFUL call's latency. Never call this for a timeout."""
        self.n += 1
        if self.ema is None:
            self.ema = seconds
            return
        d = seconds - self.ema
        self.ema += self.alpha * d
        self.ema_var = (1 - self.alpha) * (self.ema_var + self.alpha * d * d)

    def state(self) -> dict:
        return {"n": self.n, "ema": self.ema, "sd": self.ema_var ** 0.5,
                "timeout": self.timeout(),
                "phase": "bootstrap" if self.n < self.min_samples else "adaptive"}


BUDGET = LatencyBudget()


def _call(prompt: str, schema: dict, model: str, timeout: float,
          num_predict: int = 256) -> dict | None:
    """One schema-constrained judge call. Returns the parsed object, or None -- never raises.

    `num_predict` IS A PER-CALLER SETTING, NOT A CONSTANT. 256 is right for a single graded
    answer (measured 89 output tokens, `done_reason: stop`, 3x headroom). It is NOT right for a
    BATCH call: four answers x {gold_claim, answer_claim, note, score} needs ~350+ tokens, so
    the JSON is cut mid-string, `json.loads` raises, and this returns None. Measured 2026-08-30:
    that silently dropped 21 of 48 batch calls (44%) and every reported rate became a floor.

    The failure looks exactly like a timeout from the outside -- the call completes in ~25 s and
    yields nothing -- which is why it was misdiagnosed as an eviction and "fixed" by widening
    the latency budget, twice.
    """

    # JUDGE_REMOTE ROUTES THIS WHOLE MODULE, not just reward.py. Measured
    # 2026-09-15: score_arms imports judge directly, so with JUDGE_REMOTE=1 set it
    # scored the 16-question eval on the LOCAL 4b while every straddle number on
    # the same board came from OpenRouter qwen/qwen3.5-9b via reward.py. Two
    # columns, two judges, and nothing in either log said so.
    #
    # The transport lives in reward.py (`_openrouter_call` is documented as "same
    # contract as _ollama_call"), so this delegates rather than growing a second
    # copy of it. Imported lazily: reward imports this module.
    try:
        from rlv2.judge import reward as _R
        if _R._openrouter_enabled():
            return _R._openrouter_call(prompt, schema, timeout=timeout)
    except ImportError:
        # judge.py must stand alone without reward -- but a SILENT fallback here is
        # the exact defect this block exists to fix, one level down: JUDGE_REMOTE set,
        # transport unreachable, scores quietly produced by a different judge than the
        # one the caller asked for. Say it once, loudly, then carry on locally.
        global _REMOTE_WARNED
        if os.environ.get("JUDGE_REMOTE", "").strip() in {"1", "true", "yes"}                 and not _REMOTE_WARNED:
            _REMOTE_WARNED = True
            print("[judge] JUDGE_REMOTE is set but `reward` could not be imported -- "
                  "scoring LOCALLY on %s. Numbers from this run are NOT comparable to "
                  "remote-judged ones." % JUDGE_MODEL, flush=True)
    body = json.dumps({
        "model": model,
        "prompt": prompt,
        "stream": False,
        "format": schema,
        "think": False,
        "options": {"temperature": 0.0, "num_ctx": 8192, "num_predict": num_predict},
    }).encode("utf-8")
    req = urllib.request.Request("%s/api/generate" % HOST, data=body,
                                 headers={"Content-Type": "application/json"})
    # ADAPTIVE BUDGET. `timeout` is the CEILING the caller allows; the budget may cut it
    # tighter once it has seen enough real latencies. The clock starts HERE, at the moment
    # the request goes out, so queue wait upstream is not charged against the call.
    budget = min(timeout, BUDGET.timeout())
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=budget) as r:
            payload = json.loads(r.read().decode("utf-8"))
        out = json.loads(payload.get("response") or "{}")
    except (urllib.error.URLError, TimeoutError, OSError):
        return None                              # transport/timeout: retryable, no sample
    except ValueError:
        return None                              # unparseable body: not a latency sample
    BUDGET.record(time.time() - t0)              # ONLY successes widen the budget
    return out


def _unit(x) -> float | None:
    try:
        f = float(x)
    except (TypeError, ValueError):
        return None
    if f != f:                                   # NaN
        return None
    return max(0.0, min(1.0, f))


def clamp_to_band(verdict: str, score: float) -> float:
    """Keep the judge's score on the correct side of the 0.70 line its verdict implies.

    The verdict is the decision; the score only says HOW right or HOW wrong. If the two
    disagree the verdict wins, because that is what `is_correct` -- and therefore the whole
    gate -- reads. Without this a `correct` verdict scored 0.6 would render as WRONG in the
    artifact while counting as right in the total, and the table would contradict itself.
    """
    if verdict == "correct":
        return max(CORRECT_FLOOR, min(1.0, score))
    return max(0.0, min(CORRECT_FLOOR - 0.01, score))


def combine(verdict: str, quality: float, conciseness: float) -> float:
    """Band from the verdict, position within the band from quality.

    Conciseness is folded into quality at 1:3 rather than given its own band: shorter is
    PREFERRED, but a terse wrong answer must not outrank a slightly verbose right one, and
    only the verdict may cross the band boundary.
    """
    q = 0.75 * quality + 0.25 * conciseness
    if verdict == "correct":
        return round(CORRECT_FLOOR + (1.0 - CORRECT_FLOOR) * q, 4)
    if verdict == "incorrect":
        # STRICTLY BELOW THE FLOOR. The old top was CORRECT_FLOOR itself, so a fluent-wrong
        # answer with quality 1.0 scored exactly 0.7000 -- ON the correct line. `is_correct`
        # reads the verdict so the gate never mis-counted it, but the SCORE is what RL uses
        # as reward and what any downstream threshold reads, and there it rendered as
        # correct-tier. `clamp_to_band` already used CORRECT_FLOOR - 0.01 as the ceiling for
        # this exact reason; the two paths now agree.
        return round((CORRECT_FLOOR - 0.01) * q, 4)
    return 0.0                                   # not_attempted


FAILED = {"verdict": "not_attempted", "score": 0.0, "quality": 0.0, "conciseness": 0.0,
          "self_sufficient": False, "why": "unparseable", "ok": False}


def parse(q_raw: dict | None, v_raw: dict | None) -> dict:
    """Merge the two responses. FAILS CLOSED to not_attempted / 0.0 / ok=False.

    Never defaults to `correct`: a judge that silently passes on a parse error manufactures
    lift out of an outage, and the resulting number is indistinguishable from a real one.
    """
    if not isinstance(v_raw, dict):
        return dict(FAILED)
    v = str(v_raw.get("verdict", "")).strip().lower()
    if v not in VERDICTS:
        return dict(FAILED)

    quality = _unit((q_raw or {}).get("quality"))
    if quality is None:
        return dict(FAILED)
    conc = _unit((q_raw or {}).get("conciseness"))
    if conc is None:
        conc = quality                           # tolerate a missing sub-score

    # THE DERIVED SCORE WINS. The judge's own number is bimodal and carries no resolution:
    # measured 2026-08-29 over three judges on the same 12 rubric questions, the gold band
    # collapsed to sd 0.014 (9b), 0.000 (4b) and 0.025 (2b), and on the base model's 48-observation
    # eval run all 13 correct answers scored exactly 0.950. A score with no within-verdict
    # variance is a relabelled binary: it cannot rank two correct answers, and GRPO ranks
    # rollouts by advantage WITHIN a group, so a group of correct rollouts all scoring 0.95
    # yields zero advantage and no gradient.
    #
    # `quality` does vary (sd 0.363 over those same 48 observations) because it is asked for
    # blind, without the gold. `combine` turns that into position within the verdict's band,
    # which is the resolution the instrument needs. The judge's raw score is kept only as
    # diagnostic output, never as the score.
    #
    # This restores the original contract, which `test_a_score_field_from_the_judge_is_IGNORED`
    # documents. That test was failing because the code regressed away from it -- it is not
    # a stale test.
    score = combine(v, quality, conc)
    raw_score = _unit(v_raw.get("score"))

    return {"verdict": v,
            "score": score,
            "judge_score": raw_score,            # diagnostic only -- see above, never the score
            "quality": quality,
            "conciseness": conc,
            "self_sufficient": bool((q_raw or {}).get("self_sufficient", False)),
            "why": str(v_raw.get("why", ""))[:200], "ok": True}


def should_escalate(reads, floor=None):
    """True when the reads disagree about which SIDE of the floor an answer is on.

    ONE DEFINITION, USED BY BOTH SCORING PATHS. Operator 2026-09-16, on finding the
    trainer's eval reading 5/16 where score_arms read 6/16 on the same checkpoint: "This
    sounds like a bug of change we still haven't resolved". It was -- escalation was added
    to score_arms and not to the trainer, so a question sitting near the floor was resolved
    by five reads in one path and three in the other. That is the two-grader problem
    growing back in a new place, which is why the rule lives here rather than in either
    caller.

    A read that failed to parse is MISSING, not a vote: it can neither trigger an
    escalation nor block one, because an outage is not a disagreement.
    """
    f = CORRECT_FLOOR if floor is None else floor
    votes = [r for r in reads if r is not None]
    if len(votes) < 2:
        return False
    return len({v >= f for v in votes}) > 1


def parse_score(raw: dict | None) -> dict:
    """One number in, verdict DERIVED from it. FAILS CLOSED to score 0.0 / ok=False.

    TWO FIELDS (operator 2026-09-16: "Its two fields / Reasoning / Score"). The verdict is
    not a separate judgement, it is a reading of where the score fell relative to
    CORRECT_FLOOR -- so `is_correct` and the score are two views of ONE number and cannot
    disagree by construction.

    WHAT THIS REPLACED, and the defect the change surfaced. The schema used to carry an
    `answer_states_gold_claim` boolean that decided the SIDE while the number decided the
    POSITION, and this parser returned FAILED when it was absent. Dropping the field from
    the schema without rewriting the parser made every judgement come back score 0.00 --
    16 of 16, identical 54-token replies -- which reads exactly like a model that hates
    every answer rather than a parser rejecting them all. Caught by the scores being too
    uniform to be real, not by an exception.

    Never defaults to `correct`: a judge that silently passes on a parse error manufactures
    lift out of an outage, and the resulting number is indistinguishable from a real one.
    """
    if not isinstance(raw, dict):
        return dict(FAILED)
    score = _unit(raw.get("score"))
    if score is None:
        return dict(FAILED)

    # A REPLY WITH NO REASONING IS NOT A JUDGEMENT. The rubric asks the model to write the
    # gold's claim, the answer's claim, whether the answer states it, and the shortcoming
    # BEFORE placing the number -- that ordering is the whole guard against scoring a
    # deferral as correct (rubric item r3-0057). A bare number means the ordering did not
    # happen, so it fails closed rather than being trusted.
    reasoning = str(raw.get("reasoning") or raw.get("why") or "").strip()
    if not reasoning:
        return dict(FAILED)

    verdict = "correct" if score >= CORRECT_FLOOR else "incorrect"
    return {"verdict": verdict,
            "score": score,
            "quality": score,          # one axis now; kept so existing readers do not KeyError
            "conciseness": score,
            "self_sufficient": score >= CORRECT_FLOOR,
            # kept for readers that expect them; the schema no longer asks for them
            "gold_claim": "",
            "answer_claim": "",
            # nothing can disagree with a single number, but the key stays so receipts and
            # dashboards written against the old shape keep parsing.
            "score_disagreed_with_reasoning": False,
            "reasoning": reasoning[:400],
            "why": reasoning[:200], "ok": True}



_PLAN_HEADER = re.compile(
    r"^\s*(thinking process|reasoning|plan|approach|analysis|steps?)\s*[:\-]",
    re.I)
# A line that is only an enumeration marker and its label: "1. Analyze the Request",
# "- Identify the base case". Committing text does not look like this.
# WHITESPACE AFTER A NUMERIC MARKER IS REQUIRED. With `\s*` the numeral branch
# matched any DECIMAL: "0.25" parsed as item "0." followed by "25", so every bare
# numeric answer was classified a plan item and scored 0.0. Measured 2026-09-18 on
# the canonical eval -- never_states_an_answer() returned True for the GOLD STRING
# "0.25" itself, and for the model's correct "0.5^2 = 0.25.". A gate that rejects
# its own gold is broken by construction. Bullets keep `\s*`; only the numeral
# branch was ambiguous with decimals.
_PLAN_ITEM = re.compile(r"^\s*(?:\d+[.)]\s+|[-*•]\s*)\S")

# A PLAN ITEM IS SHORT. The docstring promises False for "anything that contains a
# declarative sentence", but an enumerated ANSWER ("1. Selecting alpha by eyeballing
# training error is statistically unsound because ...", 20 words) matched the item
# pattern and was zeroed too. The measured preambles are imperatives of 2-5 words
# ("Analyze the Request.", "Recall the formula."); answers run 12-40. Eight words
# separates them with margin on both sides.
_PLAN_ITEM_MAX_WORDS = 8


def never_states_an_answer(answer: str) -> bool:
    """True when the response is a plan or preamble that commits to no claim.

    Spec: none yet -- promote to a REQ before anything else depends on it.
    Basis: operator 2026-09-15, "put this in a docstring as a post process ...
    Not in the prompt!"

    Deterministic, and deliberately narrow. Returns True only when:

      1. the text is nothing but a plan header ("Thinking Process:") with no prose
         after it, or
      2. every non-empty line is an enumeration item -- a list of things the model
         intends to do, with no sentence that asserts anything.

    Returns False for anything that contains a declarative sentence, including
    answers that OPEN with planning language and then answer. That asymmetry is the
    point: a false zero on a correct answer corrupts the measurement in the direction
    that cannot be recovered, while a missed preamble is caught downstream by the
    rubric's 0.00-0.10 content-free band.
    """
    text = (answer or "").strip()
    if not text:
        return True                      # the empty guard also covers this
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    if not lines:
        return True

    # (1) a plan header and nothing that follows it
    if _PLAN_HEADER.match(lines[0]) and len(lines) == 1:
        return True

    body = lines[1:] if _PLAN_HEADER.match(lines[0]) else lines
    if not body:
        return True

    # (2) every remaining line is a SHORT enumeration item -> a list of intentions.
    # Length is what separates "3. Compute the value." from an enumerated answer;
    # without it the asymmetry the docstring promises runs the wrong way.
    def _is_plan_item(line):
        if not _PLAN_ITEM.match(line):
            return False
        rest = re.sub(r"^\s*(?:\d+[.)]|[-*•])\s*", "", line)
        return len(rest.split()) <= _PLAN_ITEM_MAX_WORDS

    return all(_is_plan_item(l) for l in body)


def echoes_question(question: str, answer: str, n: int = 6) -> bool:
    """True when the answer opens with the question's own first `n` words (tasks.md #51).

    Measured 2026-09-27: RL under the Jev judge learned to repeat the question back --
    16.4% of the capped transfer run's answers opened with the question verbatim, and the
    judge paid 326 of those 490. Checked against every gold: 0 of 16 eval golds, 0 of 40
    held-out golds and 3 of 240 training golds open with their question, and those 3 are
    records whose gold IS the question text (r3-0567/0570/0571, a data defect). A looser
    rule (80% shared words) rejected 15 real golds, so this stays an opening-words match.
    """
    q = re.findall(r"[a-z0-9]+", (question or "").lower())
    a = re.findall(r"[a-z0-9]+", (answer or "").lower())
    return len(q) >= n and len(a) >= n and a[:n] == q[:n]


def judge(question: str, gold: str, answer: str, category: str = "",
          model: str = JUDGE_MODEL, retries: int = 2,
          timeout: float = 180.0) -> dict:
    """One graded answer, ONE call. Never raises."""
    # Spec: .spec/specs/r3-domain-injection/tasks.md #35 (empty-answer guard).
    # An empty answer is wrong BY DEFINITION in this binary-correctness lane; it never
    # reaches the LLM. The train-reward path had no such guard and the judge hallucinated
    # a pass for a blank answer (past9_v2p3: `[reward-sample] len=0 | ''` -> `4/4 correct
    # at 0.70`). Same defect class exists here; closed the same way, failing closed to a
    # deterministic incorrect/0.0 with ok=True (this IS a measurement, not a failure).
    if not answer or not answer.strip():
        return {"verdict": "incorrect", "score": 0.0, "quality": 0.0, "conciseness": 0.0,
                "self_sufficient": False, "why": "empty answer — scored without the judge",
                "ok": True}
    # STUB GUARD (2026-09-06, measured on the final board): 'The prediction is:' and
    # 'The relationship is:' were graded correct by the LLM. An answer whose text
    # ends in a colon asserts NOTHING — it is a truncated frame, the same class as
    # the empty answer, and it never reaches the judge. Same law as the empty guard:
    # the LLM judge pays for silence unless a mechanical gate stops it.
    if answer.strip().endswith(":"):
        return {"verdict": "incorrect", "score": 0.0, "quality": 0.0, "conciseness": 0.0,
                "self_sufficient": False, "why": "content-free stub (ends in a colon, "
                "no claim) — scored without the judge", "ok": True}
    # PREAMBLE GUARD. Operator 2026-09-15: "We have hard filters (no eos = 0),
    # abstain answer is also 0, no need to change the prompt" -- so this is a
    # MECHANICAL post-process beside the other two gates, not an instruction added
    # to the rubric. A rubric edit saying the same thing was reverted; the rule
    # lives here, in code, where it is deterministic and testable.
    #
    # THE MEASURED FAILURE (2026-09-11): all sixteen eval responses were reasoning
    # preambles cut off by the token budget, and the judge scored every one of them
    # at or above 0.70. A response that plans, restates the question, or lists what
    # it is about to do is NOT an answer, however on-topic it reads.
    #
    # WHAT THIS CATCHES AND WHAT IT DOES NOT. The budget-truncated case is already
    # caught upstream by the EOS gate (no stop token -> reward 0), so this exists for
    # the narrower case that gets past it: a response that terminates cleanly having
    # committed to nothing. It is deliberately HIGH PRECISION rather than complete --
    # a plan header with nothing after it, or text ending mid-enumeration. It does NOT
    # attempt to detect "on-topic but vacuous" prose, because every heuristic for that
    # also fires on correct answers that happen to open with "Let me compute...", and
    # a false zero on a right answer is worse than a missed zero on a wrong one. That
    # residue is the rubric's 0.00-0.10 content-free band, which already covers it.
    if never_states_an_answer(answer):
        return {"verdict": "incorrect", "score": 0.0, "quality": 0.0, "conciseness": 0.0,
                "self_sufficient": False, "why": "never states an answer (plan/preamble "
                "with no claim) — scored without the judge", "ok": True}
    # ECHO GUARD (tasks.md #51): the question repeated back is not an answer.
    if echoes_question(question, answer):
        return {"verdict": "incorrect", "score": 0.0, "quality": 0.0, "conciseness": 0.0,
                "self_sufficient": False, "why": "repeats the question -- scored without "
                "the judge", "ok": True}
    # JUDGE_JEV routes THIS path too (2026-09-26). score_arms -- the per-epoch SFT eval --
    # calls judge.judge, not reward.llm_judge_batch_train, so without this the SFT re-pick
    # under Jev would have been scored by the 9B while its log said nothing about it.
    try:
        from rlv2.judge import reward as _R
    except ImportError:
        _R = None
    if _R is not None and _R._jev_enabled():
        if not _R._jev_gate(gold, answer):
            return {"verdict": "incorrect", "score": 0.0, "quality": 0.0, "conciseness": 0.0,
                    "self_sufficient": False, "why": "jev gate: short-numeric mismatch or no content "
                    "overlap with the reference -- scored without the judge", "ok": True}
        _p = _R._jev_p_yes(question, gold, answer)
        _ok = _p >= _R._jev_load()["thr"]
        return {"verdict": "correct" if _ok else "incorrect", "score": 1.0 if _ok else 0.0,
                "quality": 0.0, "conciseness": 0.0, "self_sufficient": _ok,
                "why": f"open-jev-2b p_yes={_p:.3f}", "ok": True}
    for _ in range(max(1, retries)):
        # num_predict 256 assumed a SHORT gold. Measured 2026-09-07 on eval item
        # r3-0640 (gold ~300 chars, prompt 13.6k): the schema echoes gold_claim
        # before scoring, so the reply is cut mid-JSON, parse fails, and three
        # retries later the cell reports "judge unavailable" — a permanently
        # unscoreable question that silently became a zero on every arm. The same
        # call with room parses in 31 s.
        out = parse_score(_call(build_score_prompt(question, gold, answer, category),
                                _SCORE_SCHEMA, model, timeout, num_predict=768))
        if out["ok"]:
            return out
    return dict(FAILED, why="judge unavailable")


def is_correct(result: dict) -> bool:
    """The binary the CPT/SFT gate reads. `not_attempted` is NOT correct -- and it is also
    not the same failure as `incorrect`, which is why the verdict keeps three values even
    though the gate collapses them to two."""
    return result.get("verdict") == "correct"
