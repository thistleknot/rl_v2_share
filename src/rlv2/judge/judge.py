"""src/rlv2/judge/judge.py — ONE reasoned score per answer, from one local judge.

Notes: docs/dispositions.md "JUDGE CHANGE" and "JEV GATE adopted" (2026-09-26); concept: Inverse RL /
Reward Modeling (docs/INSPIRATIONS.md). Slides: docs/PROVENANCE.md rows for RL deck slides 8, 9 and 22.

REQ-J1/J2. One call returns the judge's reasoning and then a single number, and the verdict
is DERIVED from where that number falls:

    score    0.0-1.0, placed against the rubric's scale, gold in hand
    verdict  correct if score >= 0.70, else incorrect   <- read, not separately asserted

SUPERSEDES THE TWO-CALL FORM (owner decision, 2026-08-29). The earlier design asked for a
verdict in one call and a blind quality score in another, then combined them. Asking the same
question twice in two formats means the two answers can disagree, and they did: on rubric item
r3-0057 the judge returned verdict `correct` with quality `0.0`, and band arithmetic quietly
arbitrated the contradiction into a passing 0.700. One number cannot contradict itself.

THE REASONING COMES FIRST, AND THAT IS THE MECHANISM. Constrained decoding emits schema
properties in declaration order, so a schema of {score, why} produces a number and then a
rationalisation of it. `_SCORE_SCHEMA` therefore requires the judge to write the gold's claim,
the answer's claim, whether the answer states the gold's claim, and what holds it back --
BEFORE it may emit a score. Measured effect on the r3-0057 deferral: `correct 0.700` became
`incorrect 0.450` with the reason "agrees with the standard approach".

WHY A GRADED SCORE AT ALL, RATHER THAN A BARE BINARY. GRPO ranks WITHIN a group; a binary
reward makes every member of a group identical and drives `frac_reward_zero_std` to 1, which
is the known RL stall. Judges are measurably COMPRESSED and LENIENT (arXiv:2605.16386
central-tendency bias; arXiv:2602.17170 inflation), so the rubric has to DEMONSTRATE the range
rather than assert it -- every judge tested collapsed the gold band to sd <= 0.025 while the
rubric's four worked examples all scored 0.95.

FAILS CLOSED. A malformed judge response returns `not_attempted` with score 0.0 and
`ok=False`. It must never default to `correct`: a judge that silently passes on a parse
error manufactures lift out of an outage.

Require   - ollama reachable at HOST with JUDGE_MODEL pulled; the rubric file present.
Guarantee - always returns a dict with verdict/score/ok; never raises to the caller.
Maintain  - the rubric is read from ONE file and hashed; the judge model id is recorded
            beside it so a run receipt can prove which instrument produced a number.
Assert    - verdict is one of the three literals; score is clamped to [0, 1].
"""
