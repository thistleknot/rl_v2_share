"""docs/ast_outline.py -- regenerate the AST breakdown of src/rlv2/ inside README.md.

Spec: C:/Users/user/.claude/plans/virtual-sauteeing-crown.md Layer 3 (task 9).
NO GOVERNING SPEC in the repo's .spec tree; basis is the operator-approved restructure plan.

For each module under rlv2/ it lists, from the AST alone (nothing is imported or run):
the first docstring line, every public class and function with its first docstring line,
and a count of private helpers. The block between the two markers in README.md is replaced.

    python docs/ast_outline.py            # rewrite the README block
    python docs/ast_outline.py --check    # exit 1 if the README block is stale
"""
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = os.path.join(ROOT, "README.md")
BEGIN, END = "<!-- AST-OUTLINE:BEGIN (generated by docs/ast_outline.py; do not edit) -->", "<!-- AST-OUTLINE:END -->"
STAGE_ORDER = ["", "common", "judge", "data", "train/cpt", "train/sft", "train/rl", "train/hpo", "train", "eval"]


def first_line(doc, width=110):
    """First docstring line, without a leading 'path/file.py --' prefix, cut to `width` chars."""
    if not doc:
        return ""
    line = re.sub(r"^[\w/\.]+\.py\s+(--|—)\s+", "", doc.strip().splitlines()[0].strip())
    return line if len(line) <= width else line[:width - 3].rstrip() + "..."


def outline_module(path):
    tree = ast.parse(open(path, encoding="utf-8").read())
    n_lines = sum(1 for _ in open(path, encoding="utf-8"))
    public, private = [], 0
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if node.name.startswith("_"):
                private += 1
                continue
            kind = "class" if isinstance(node, ast.ClassDef) else "def"
            public.append((kind, node.name, first_line(ast.get_docstring(node))))
    return first_line(ast.get_docstring(tree)), n_lines, public, private


def build():
    pkgs = {}
    base = os.path.join(ROOT, "src", "rlv2")
    for dp, dn, fs in os.walk(base):
        dn[:] = sorted(d for d in dn if d != "__pycache__")
        for f in sorted(fs):
            if f.endswith(".py"):
                rel = os.path.relpath(os.path.join(dp, f), base).replace(os.sep, "/")
                pkg = rel.rsplit("/", 1)[0] if "/" in rel else ""
                pkgs.setdefault(pkg, []).append(rel)
    out = []
    for pkg in sorted(pkgs, key=lambda p: STAGE_ORDER.index(p) if p in STAGE_ORDER else 99):
        out.append(f"\n**`src/rlv2/{pkg + '/' if pkg else ''}`**\n")
        for rel in pkgs[pkg]:
            if rel.endswith("__init__.py"):
                continue
            summary, n, public, private = outline_module(os.path.join(base, rel))
            out.append(f"- `{rel}` ({n} lines) {summary}")
            for kind, name, doc in public:
                out.append(f"  - `{kind} {name}`" + (f": {doc}" if doc else ""))
            if private:
                out.append(f"  - {private} private helpers")
    return "\n".join(out).strip("\n")


def main(argv):
    block = f"{BEGIN}\n\n{build()}\n\n{END}"
    text = open(README, encoding="utf-8", newline="").read()
    nl = "\r\n" if "\r\n" in text else "\n"
    block = block.replace("\n", nl)
    if BEGIN not in text or END not in text:
        print("README.md has no AST-OUTLINE markers", file=sys.stderr)
        return 2
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + block + tail
    if "--check" in argv:
        return 0 if new == text else 1
    open(README, "w", encoding="utf-8", newline="").write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
